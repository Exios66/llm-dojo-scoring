"""The CircleCI link guard rejects session links and attribution footers."""

from __future__ import annotations

import os
import re
import stat
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / ".circleci" / "check_no_session_links.sh"

MUST_MATCH = [
    "https://claude.ai/code/session_abc",
    "https://claude.ai/",
    "https://www.claude.ai/newpath",
    "http://claude.ai",
    "claude.ai/share/abc",
    "https://claude.com/claude-code",
    "https://claude.com/code/session_x",
    "Claude-Session: abc",
    "  Claude-Session: abc",
    "Generated with [Claude Code]",
    "Generated by [Claude Code]",
    "Generated with Claude Code",
    "🤖 Generated with Claude Code",
    "> Generated with Claude Code",
    "- Generated with Claude Code",
    "* Generated with Claude Code",
    "+ Generated with Claude Code",
]

MUST_NOT_MATCH = [
    "fix(scoring): keep the golden baseline",
    "see claude.ai for the policy text",
    "https://claude.com/docs",
    "Co-Authored-By: Ada <ada@example.com>",
    'a "Generated with Claude Code" footer is discussed here',
    "note: Generated with Claude Code in the middle",
    "Generated with/by Claude Code",
]


def pattern() -> str:
    """Return the guard's extended regular expression."""
    text = SCRIPT.read_text(encoding="utf-8")
    found = re.search(r"^PATTERN='(.*)'$", text, re.M)
    assert found, "PATTERN assignment missing"
    return found.group(1)


def grep_matches(text: str) -> bool:
    """Match ``text`` with the same grep flags the guard uses."""
    result = subprocess.run(
        ["grep", "-Ei", pattern()],
        input=text,
        text=True,
        capture_output=True,
        check=False,
    )
    assert result.returncode in (0, 1)
    return result.returncode == 0


@pytest.mark.parametrize("sample", MUST_MATCH)
def test_pattern_matches_leaks(sample):
    """Session links, product URLs, trailers, and footers fail the guard."""
    assert grep_matches(sample)


@pytest.mark.parametrize("sample", MUST_NOT_MATCH)
def test_pattern_ignores_ordinary_text(sample):
    """Policy prose and ordinary commit text stay allowed."""
    assert not grep_matches(sample)


def _git(repo: Path, *args: str) -> None:
    """Run git in ``repo`` and raise if it fails."""
    subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True)


def _commit(repo: Path, message: str) -> None:
    """Create an empty commit so the guard has a message to read."""
    _git(repo, "-c", "user.email=test@example.com", "-c", "user.name=Test", "commit", "--allow-empty", "-m", message)


def _run(repo: Path, env: dict[str, str], curl: Path | None = None) -> subprocess.CompletedProcess[str]:
    """Run the guard in ``repo`` with a clean environment and an optional curl stub."""
    path = str(repo / "bin") + os.pathsep + os.environ.get("PATH", "")
    if curl is not None:
        bindir = repo / "bin"
        bindir.mkdir(exist_ok=True)
        curl_path = bindir / "curl"
        curl_path.write_text(curl.read_text(encoding="utf-8"), encoding="utf-8")
        curl_path.chmod(curl_path.stat().st_mode | stat.S_IEXEC)
    full = {
        "PATH": path,
        "HOME": os.environ.get("HOME", ""),
        "CIRCLE_BRANCH": env.get("CIRCLE_BRANCH", "main"),
    }
    full.update(env)
    return subprocess.run(
        ["bash", str(SCRIPT)],
        cwd=repo,
        env=full,
        text=True,
        capture_output=True,
        check=False,
    )


def _repo(tmp_path: Path, message: str) -> Path:
    """Create a one-commit repository whose HEAD message is ``message``."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-b", "main")
    _commit(repo, message)
    return repo


def test_clean_head_passes(tmp_path):
    """A clean squash commit passes when no pull request is attached."""
    repo = _repo(tmp_path, "ci: add the link guard")
    result = _run(repo, {"CIRCLE_BRANCH": "main"})
    assert result.returncode == 0, result.stderr
    assert "description not checked" in result.stdout


def test_footer_on_head_fails_without_printing_the_text(tmp_path):
    """A product URL fails the guard, and the log does not repeat it."""
    repo = _repo(tmp_path, "https://claude.com/claude-code")
    result = _run(repo, {"CIRCLE_BRANCH": "main"})
    assert result.returncode == 1
    assert "https://claude.com" not in result.stdout
    assert "https://claude.com" not in result.stderr
    assert "commit message" in result.stderr


def test_branch_scans_commits_not_on_main(tmp_path):
    """A branch build scans every commit that is not yet on main."""
    bare = tmp_path / "origin.git"
    subprocess.run(["git", "init", "--bare", "-b", "main", str(bare)], check=True, capture_output=True)
    repo = _repo(tmp_path, "ci: base")
    _git(repo, "remote", "add", "origin", str(bare))
    _git(repo, "push", "origin", "main")
    _git(repo, "checkout", "-b", "feature")
    _commit(repo, "- Generated with Claude Code")
    result = _run(repo, {"CIRCLE_BRANCH": "feature"})
    assert result.returncode == 1, result.stderr
    assert "Generated with" not in result.stderr


def test_every_attached_pull_request_is_read(tmp_path):
    """Every pull request on the build is read, not only the one CircleCI names."""
    repo = _repo(tmp_path, "ci: clean")
    curl = tmp_path / "curl-stub"
    curl.write_text(
        """#!/bin/sh
url=
for arg in "$@"; do
  case "$arg" in
    https://*) url=$arg ;;
  esac
done
printf '%s\\n' "$url" >> "$CURL_LOG"
case "$url" in
  *pulls/2)
    printf '%s\\n' '{"title":"Generated with Claude Code","body":""}'
    ;;
  *)
    printf '%s\\n' '{"title":"ci: guard","body":"ordinary"}'
    ;;
esac
""",
        encoding="utf-8",
    )
    log = tmp_path / "curl.log"
    result = _run(
        repo,
        {
            "CIRCLE_BRANCH": "main",
            "CIRCLE_PULL_REQUEST": "https://github.com/acme/widgets/pull/1",
            "CIRCLE_PULL_REQUESTS": "https://github.com/acme/widgets/pull/1, https://github.com/acme/widgets/pull/2",
            "CURL_LOG": str(log),
        },
        curl=curl,
    )
    assert result.returncode == 1, result.stderr + result.stdout
    seen = log.read_text(encoding="utf-8")
    assert "pulls/1" in seen
    assert "pulls/2" in seen
    assert "Generated with" not in result.stderr


def test_unread_description_warns_and_does_not_fail(tmp_path):
    """An unreadable pull request warns and leaves a clean commit passing."""
    repo = _repo(tmp_path, "ci: clean")
    curl = tmp_path / "curl-fail"
    curl.write_text("#!/bin/sh\nexit 22\n", encoding="utf-8")
    result = _run(
        repo,
        {
            "CIRCLE_BRANCH": "main",
            "CIRCLE_PULL_REQUEST": "https://github.com/acme/widgets/pull/9",
        },
        curl=curl,
    )
    assert result.returncode == 0, result.stderr
    assert "description not checked" in result.stderr

"""Golden-number baseline for every task kind and every live suite (issue #67).

The committed fixture is the source of truth: ``inputs.json`` is hand-authored,
``scores.json`` is generated by ``scripts/freeze_goldens.py``. This test only
reads both files, recomputes the scores in memory, and compares canonical JSON.
No network and no mocks are used for the golden values.
"""

from __future__ import annotations

import importlib.util
import json
import math
from difflib import unified_diff
from pathlib import Path

import pytest

from llm_dojo_scoring.config import TASK_KINDS, clear_settings_cache, get_settings
from llm_dojo_scoring.metrics.scorecard_honesty import SCORER_VERSION
from llm_dojo_scoring.scoring.suites import get_suite, list_suites

_GOLDEN_DIR = Path(__file__).resolve().parent / "fixtures" / "golden"
_INPUTS_PATH = _GOLDEN_DIR / "inputs.json"
_SCORES_PATH = _GOLDEN_DIR / "scores.json"
_FREEZE_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "freeze_goldens.py"


def _load_freeze_module():
    """Import the freeze script by path so the test shares its collector."""
    spec = importlib.util.spec_from_file_location("_freeze_goldens", _FREEZE_SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_FREEZE = _load_freeze_module()
_INPUTS = json.loads(_INPUTS_PATH.read_text(encoding="utf-8"))
_COMMITTED = json.loads(_SCORES_PATH.read_text(encoding="utf-8"))


@pytest.fixture(autouse=True)
def _default_scoring_settings(monkeypatch):
    """Clear cached settings and prove the default ambiguous band before scoring."""
    monkeypatch.delenv("LLM_DOJO_SCORING_CONFIG", raising=False)
    clear_settings_cache()
    try:
        assert get_settings().field_scoring.ambiguous_band == (0.5, 0.85)
        yield
    finally:
        clear_settings_cache()


def test_global_settings_are_default_before_scoring():
    """Golden numbers must be produced with the package's default settings."""
    settings = get_settings()
    assert settings.field_scoring.ambiguous_band == (0.5, 0.85)
    assert settings.field_scoring.embedding_enabled is False
    assert settings.trace_knobs.missing_confidence == "absent"


def test_every_task_kind_has_a_golden_case():
    """Every TASK_KINDS key has an input entry and a committed score entry.

    A new task key without an input case must fail here, never skip.
    """
    expected = set(TASK_KINDS)
    actual = set(_INPUTS["task_cases"])
    assert not expected - actual, f"missing golden task cases: {sorted(expected - actual)}"
    assert not actual - expected, f"unexpected golden task cases: {sorted(actual - expected)}"
    assert set(_COMMITTED["task_kinds"]) == expected
    for task, kind in TASK_KINDS.items():
        assert _COMMITTED["task_kinds"][task]["kind"] == kind

    chained = _INPUTS["task_cases"]["chained"]
    assert chained["guard"]["raises"] == "ValueError"
    assert chained["summary"]
    frozen_chained = _COMMITTED["task_kinds"]["chained"]
    assert frozen_chained["score_task_guard"]["raises"] == "ValueError"
    assert frozen_chained["chained_summary"]


def test_every_live_suite_has_a_golden_entry():
    """Every live suite has an input entry and a committed score entry.

    A new live suite without an input case must fail here, never skip.
    """
    expected = set(list_suites(live_only=True))
    actual = set(_INPUTS["suite_cases"])
    assert not expected - actual, f"missing golden suite cases: {sorted(expected - actual)}"
    assert not actual - expected, f"unexpected golden suite cases: {sorted(actual - expected)}"
    assert set(_COMMITTED["suites"]) == expected

    for name in sorted(expected):
        suite = get_suite(name)
        entry = _COMMITTED["suites"][name]
        assert entry["kind"] == suite.kind
        assert entry["computable"] is suite.computable
        if suite.kind == "extraction":
            assert "score" in entry, name
            assert "score_document" in entry, name


def test_non_computable_suites_raise_type_error():
    """Emit-only suites refuse to score and record their metric surface."""
    for name in ("reporter", "boss", "archivist"):
        suite = get_suite(name)
        assert suite.computable is False
        with pytest.raises(TypeError):
            suite.score(None, None)
        entry = _COMMITTED["suites"][name]
        assert entry == {
            "computable": False,
            "kind": suite.kind,
            "score_raises": "TypeError",
            "metric_names": suite.metric_names(),
        }


def test_golden_scores_match_committed_baseline():
    """Recompute every case and compare against the committed canonical baseline."""
    regenerated = _FREEZE.render_goldens(_FREEZE.collect_goldens(_INPUTS))
    committed = _SCORES_PATH.read_text(encoding="utf-8")
    if regenerated != committed:
        diff = "".join(
            unified_diff(
                committed.splitlines(keepends=True),
                regenerated.splitlines(keepends=True),
                fromfile=str(_SCORES_PATH),
                tofile=f"{_SCORES_PATH} (regenerated)",
            )
        )
        pytest.fail(
            "golden scores drifted from the committed baseline:\n" + diff
        )


def test_committed_baseline_is_canonical_json():
    """The baseline uses sorted keys, 2-space indent, and exactly one trailing LF."""
    text = _SCORES_PATH.read_text(encoding="utf-8")
    assert text.endswith("\n")
    assert not text.endswith("\n\n")
    assert (
        json.dumps(
            json.loads(text),
            sort_keys=True,
            indent=2,
            ensure_ascii=False,
            allow_nan=False,
        )
        + "\n"
        == text
    )


def test_score_document_payload_is_json_serializable():
    """The provenance-bearing extraction payload serializes with the real version."""
    case = _INPUTS["suite_cases"]["contracts_specialist"]
    payload = get_suite("contracts_specialist").score_document(
        case["expected"], case["predicted"]
    )
    assert payload["provenance"]["scorer_version"] == SCORER_VERSION

    canonical = _FREEZE.canonicalize(payload)
    assert canonical["provenance"]["scorer_version"] == "<SCORER_VERSION>"
    rendered = _FREEZE.render_goldens(payload)
    assert json.loads(rendered)["provenance"]["scorer_version"] == "<SCORER_VERSION>"


def test_canonicalizer_rejects_sets():
    """Sets are not JSON and must never leak into a frozen baseline."""
    with pytest.raises(TypeError, match="sets"):
        _FREEZE.canonicalize({"values": {"a", "b"}})


def test_canonicalizer_rejects_non_finite_floats():
    """NaN and infinities must fail instead of becoming non-standard JSON."""
    for value in (math.nan, math.inf, -math.inf):
        with pytest.raises(ValueError, match="non-finite"):
            _FREEZE.canonicalize({"value": value})


def test_canonicalizer_preserves_none_and_zero():
    """Missing values and real zeros stay distinct in the baseline."""
    assert _FREEZE.canonicalize({"none": None, "zero": 0.0, "int_zero": 0}) == {
        "none": None,
        "zero": 0.0,
        "int_zero": 0,
    }


# --- PR #103 review regressions -------------------------------------------


def _emit_only_case():
    """One live emit-only suite name plus its golden input case."""
    inputs = _FREEZE.load_inputs()
    for name in list_suites(live_only=True):
        if not get_suite(name).computable:
            case = inputs["suite_cases"][name]
            return name, case
    pytest.skip("no emit-only live suite")


def test_freeze_rejects_an_unrelated_type_error_from_an_emit_only_suite(monkeypatch):
    """Only the documented emit-only refusal satisfies the golden contract."""
    name, case = _emit_only_case()
    suite = get_suite(name)

    def broken_score(*_args, **_kwargs):
        """Raise a TypeError that is not the emit-only refusal."""
        raise TypeError("unsupported operand type(s) for +: 'int' and 'str'")

    monkeypatch.setattr(type(suite), "score", broken_score)
    with pytest.raises(RuntimeError, match="unexpected TypeError"):
        _FREEZE._collect_suite_case(name, case)


def test_freeze_accepts_the_documented_emit_only_refusal():
    """The real emit-only TypeError is still recorded as the contract."""
    name, case = _emit_only_case()
    out = _FREEZE._collect_suite_case(name, case)
    assert out["computable"] is False
    assert out["score_raises"] == "TypeError"


def test_freeze_write_restores_the_baseline_when_recollection_fails(monkeypatch, tmp_path):
    """A crash in the idempotence pass must not leave an unverified baseline."""
    scores = tmp_path / "scores.json"
    scores.write_text("previous\n", encoding="utf-8")
    monkeypatch.setattr(_FREEZE, "SCORES_PATH", scores)
    calls = {"n": 0}
    real_collect = _FREEZE.collect_goldens

    def flaky_collect(inputs):
        """Fail on the second (idempotence) collection only."""
        calls["n"] += 1
        if calls["n"] == 2:
            raise RuntimeError("boom")
        return real_collect(inputs)

    monkeypatch.setattr(_FREEZE, "collect_goldens", flaky_collect)
    with pytest.raises(RuntimeError, match="boom"):
        _FREEZE.main(["--write", "--reason", "test"])
    assert scores.read_text(encoding="utf-8") == "previous\n"


def test_freeze_write_removes_a_new_baseline_when_recollection_fails(monkeypatch, tmp_path):
    """With no previous baseline, a failed recollection removes the new file."""
    scores = tmp_path / "scores.json"
    monkeypatch.setattr(_FREEZE, "SCORES_PATH", scores)
    calls = {"n": 0}
    real_collect = _FREEZE.collect_goldens

    def flaky_collect(inputs):
        """Fail on the second (idempotence) collection only."""
        calls["n"] += 1
        if calls["n"] == 2:
            raise RuntimeError("boom")
        return real_collect(inputs)

    monkeypatch.setattr(_FREEZE, "collect_goldens", flaky_collect)
    with pytest.raises(RuntimeError):
        _FREEZE.main(["--write", "--reason", "test"])
    assert not scores.exists()

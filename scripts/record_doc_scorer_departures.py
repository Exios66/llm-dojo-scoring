#!/usr/bin/env python3
"""Record where the current Dojo departs from the frozen per-document-type goldens.

``tests/fixtures/doc_scorers/goldens.json`` (sandbox ``score_extraction_row``, captured
at dojo 0.26.0) and ``archive_block_before.json`` (``score_archive_block`` before
0.27.0) stay as captured: they are the historical record. A release that changes
scores on purpose records the new values here instead, as an overlay the parity tests
apply, and ``tests/test_doc_scorer_departures.py`` bounds which classes, keys and
fields the overlay may touch.

0.28.0 (mailroom-dataset v10, plan G1) is the first such release:

- ContractExtraction / MergerAgreementExtraction v2 and the ``label`` retypes change
  the live field maps, so ``field_map_sha`` changes on every contract, merger,
  correspondence and insurance block;
- the contract's v1 ``merger_consideration`` / ``maud_clauses`` are parse-compat and
  no longer scored (a spurious value is no longer a false positive);
- closed ``label`` fields score by exact match after alias folding, so a wrong label
  that the old ``name`` scorer gave partial or full containment credit scores 0;
- a v1 merger prediction lacks the v2 keys, so the block's ``schema_valid`` (every
  live key present) is False.

    uv run --extra dev python scripts/record_doc_scorer_departures.py           # write
    uv run --extra dev python scripts/record_doc_scorer_departures.py --check   # exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURES = REPO_ROOT / "tests" / "fixtures" / "doc_scorers"
OUT_PATH = FIXTURES / "departures.json"

#: Keys ``assess_extraction_payload`` adds; schema adherence is not part of the overlay.
_ADHERENCE_EXTRA = {"extra_schema_key_count", "recovered_from_raw"}


def _to_jsonable(value: Any) -> Any:
    """The same JSON conversion the goldens were captured with."""
    sys.path.insert(0, str(REPO_ROOT / "scripts"))
    from capture_sandbox_goldens import to_jsonable  # noqa: PLC0415

    return to_jsonable(value)


def build() -> dict[str, Any]:
    """The overlay: per case, the payload / block keys whose value moved."""
    from llm_dojo_scoring import __version__, score_archive_block, score_document  # noqa: PLC0415

    cases = json.loads((FIXTURES / "inputs.json").read_text())["cases"]
    goldens = json.loads((FIXTURES / "goldens.json").read_text())["cases"]
    before = json.loads((FIXTURES / "archive_block_before.json").read_text())["cases"]
    payload: dict[str, dict[str, Any]] = {}
    blocks: dict[str, dict[str, dict[str, Any]]] = {}
    for case in cases:
        case_id = case["case_id"]
        golden = goldens[case_id]
        if "error" not in golden["payload"]:
            got = _to_jsonable(score_document(
                case["doc_type"], case["predicted"], case["expected"],
                doc_text=case.get("doc_text"), doc_subclass=case.get("doc_subclass"),
                expected_subclass=case.get("expected_subclass"),
            ))
            skip = set(golden["adherence"]) | _ADHERENCE_EXTRA
            moved = {
                k: got[k] for k, v in golden["payload"].items()
                if k not in skip and k in got and got[k] != v
            }
            if moved:
                payload[case_id] = moved
        old = before.get(case_id)
        if old is None or "error" in old:
            continue
        for variant, extra in (("plain", {}), ("with_subclass", {"doc_subclass": case.get("doc_subclass")})):
            got = _to_jsonable(score_archive_block(
                case["doc_type"], case["predicted"], case["expected"],
                doc_text=case.get("doc_text"), expected_subclass=case.get("expected_subclass"), **extra,
            ))
            ref = json.loads(json.dumps(old))
            got["provenance"].pop("scorer_version", None)
            ref["provenance"].pop("scorer_version", None)
            moved = {k: got[k] for k in ref if got.get(k) != ref[k]}
            if moved:
                blocks.setdefault(case_id, {})[variant] = moved
    return {
        "_comment": (
            "Generated by scripts/record_doc_scorer_departures.py. Deliberate score changes "
            "since the captured goldens; tests/test_doc_scorer_departures.py bounds them."
        ),
        "dojo_version": __version__,
        "payload": payload,
        "archive_block": blocks,
    }


def main(argv: list[str] | None = None) -> int:
    """CLI entry point; returns a process exit code."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare instead of writing")
    args = ap.parse_args(argv)
    data = build()
    text = json.dumps(data, indent=1, sort_keys=True) + "\n"
    if args.check:
        current = json.loads(OUT_PATH.read_text()) if OUT_PATH.exists() else {}
        # The version stamp moves with every release cut; the overlay itself must not.
        current.pop("dojo_version", None)
        data.pop("dojo_version", None)
        if current != json.loads(json.dumps(data)):
            print(f"DRIFT: {OUT_PATH.relative_to(REPO_ROOT)} differs from the current Dojo")
            return 1
        print("ok doc-scorer departures")
        return 0
    OUT_PATH.write_text(text)
    print(f"wrote {OUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

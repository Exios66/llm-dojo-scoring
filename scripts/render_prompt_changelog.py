"""Write or check the prompt changelog (``docs/prompts/PROMPT_CHANGELOG.md``).

One page for the prompt catalog: each production prompt's version, source and template
digest, the eval-environment version chain per role, and where the specialist prompts
disagree with the scoring schema (``llm_dojo_scoring.prompts.alignment``). ``--write``
regenerates it; ``--check`` exits 1 when the committed page is stale. Network-free.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from llm_dojo_scoring.prompts import iter_prompts, list_prompt_versions  # noqa: E402
from llm_dojo_scoring.prompts.alignment import alignment_report, recorded_gaps  # noqa: E402

DOC_PATH = ROOT / "docs" / "prompts" / "PROMPT_CHANGELOG.md"
TEMPLATES = ROOT / "llm_dojo_scoring" / "prompts" / "templates"
MEMO_CHARS = 140


def _cell(text: str) -> str:
    """One table cell: whitespace collapsed, pipes escaped."""
    return " ".join(str(text).split()).replace("|", "\\|")


def _memo(text: str) -> str:
    """The memo as one line of at most ``MEMO_CHARS`` characters."""
    line = " ".join(text.split())
    return line if len(line) <= MEMO_CHARS else line[: MEMO_CHARS - 3].rstrip() + "..."


def template_sha256(name: str | None) -> str:
    """sha256 of the template file's bytes, or ``-`` for a role without a template."""
    return hashlib.sha256((TEMPLATES / name).read_bytes()).hexdigest() if name else "-"


def render() -> str:
    """The whole page as committed."""
    out = [
        "# Prompt changelog",
        "",
        "Generated by `scripts/render_prompt_changelog.py --write`; do not edit by hand.",
        "The catalog is `llm_dojo_scoring/prompts/catalog.yaml`, the lineage is",
        "`eval_environment_lineage.json`. The digest is the sha256 of the template file bytes.",
        "",
        "## Production prompts",
        "",
        "| Agent | Kind | Version | Source | Commit | Template sha256 |",
        "|:---|:---|:---|:---|:---|:---|",
    ]
    for rec in iter_prompts():
        if rec.family != "production":
            continue
        source = f"{rec.source_repo} `{rec.source_key}`"
        out.append(
            f"| `{rec.agent}` | {rec.kind} | `{_cell(rec.version)}` | {_cell(source)} | "
            f"{rec.source_commit[:8] or '-'} | {template_sha256(rec.template)} |"
        )
    out += ["", "## Version chains (eval-environment lineage)", ""]
    roles = sorted({v.role for v in list_prompt_versions()})
    for role in roles:
        out += [
            f"### `{role}`",
            "",
            "| Version | Lineage | Created | Memo |",
            "|:---|:---|:---|:---|",
        ]
        for v in list_prompt_versions(role=role):
            out.append(f"| `{v.key}` | {v.lineage} | {v.created_at} | {_cell(_memo(v.memo))} |")
        out.append("")
    out += [
        "## Prompt <-> schema alignment",
        "",
        "Fields the scoring schema (`schemas/doc_classes.py`) scores that the production",
        "specialist prompt never asks for, and keys the prompt asks for that the schema does",
        "not score (`confidence` and `reasoning` are allowed). Recorded in",
        "`llm_dojo_scoring/prompts/data/alignment_gaps.json`; the guard test fails when this",
        "list changes. Nothing here is fixed by the Dojo: the prompts belong to llm-mailroom.",
        "",
    ]
    reasons = {(g["agent"], g["field"], g["side"]): g["reason"] for g in recorded_gaps()}
    for agent, row in alignment_report().items():
        out += [f"### `{agent}` ({row['doc_type']})", ""]
        found = False
        for side in ("missing_from_prompt", "extra_in_prompt"):
            for name in row[side]:
                found = True
                reason = reasons.get((agent, name, side), "not recorded")
                out.append(f"- `{name}` ({side.replace('_', ' ')}): {_cell(reason)}")
        if not found:
            out.append("- aligned")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    """Entry point: ``--write`` or ``--check`` (exactly one)."""
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the page")
    mode.add_argument("--check", action="store_true", help="exit 1 when the page is stale")
    parser.add_argument("--path", type=Path, default=DOC_PATH, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    fresh = render()
    if args.write:
        args.path.parent.mkdir(parents=True, exist_ok=True)
        args.path.write_text(fresh, encoding="utf-8")
        print(f"wrote {args.path.name}")
        return 0
    current = args.path.read_text(encoding="utf-8") if args.path.exists() else ""
    if current == fresh:
        print(f"{args.path.name} is current")
        return 0
    print(f"{args.path.name} is stale", file=sys.stderr)
    print("run: uv run --locked python scripts/render_prompt_changelog.py --write", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
